def main():
    print(f"🍳 {SITE_NAME} サイト生成を開始します...")
    print(f"レシピ数: {len(RECIPES)}")

    # ディレクトリ作成
    os.makedirs(os.path.join(BASE_DIR, "recipes"), exist_ok=True)
    os.makedirs(os.path.join(BASE_DIR, "css"), exist_ok=True)

    # 個別レシピページ生成
    for recipe in RECIPES:
        html = generate_recipe_html(recipe)
        filepath = os.path.join(BASE_DIR, "recipes", f"{recipe['id']}.html")
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(html)
        print(f"  ✅ {recipe['name']} → recipes/{recipe['id']}.html")

    # トップページ生成
    index_html, recipe_links = generate_index_html()
    with open(os.path.join(BASE_DIR, "index.html"), "w", encoding="utf-8") as f:
        f.write(index_html)
    print(f"  ✅ index.html")

    # sitemap.xml
    sitemap = generate_sitemap(recipe_links)
    with open(os.path.join(BASE_DIR, "sitemap.xml"), "w", encoding="utf-8") as f:
        f.write(sitemap)
    print(f"  ✅ sitemap.xml")

    # robots.txt
    robots = f"""User-agent: *
Allow: /
Sitemap: {SITE_URL}/sitemap.xml"""
    with open(os.path.join(BASE_DIR, "robots.txt"), "w", encoding="utf-8") as f:
        f.write(robots)
    print(f"  ✅ robots.txt")

    print(f"\n🎉 生成完了！合計 {len(RECIPES)} レシピのページを作成しました。")


if __name__ == "__main__":
    main()
